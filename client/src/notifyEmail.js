/** เปิดหน้าเขียนเมลใน Gmail พร้อมข้อความ ต้องเรียกตอนกดปุ่มทันที ไม่งั้นเบราว์เซอร์บล็อกป๊อปอัป */
export function openNotifyEmail(q) {
  // คิวเก่าอาจมีอีเมลของลูกค้าเอง ถ้าไม่มี (รวมถึงคิวใหม่ทั้งหมด) ใช้อีเมลที่มีปัญหาแทน
  const to = q.notify_email || q.problem_email;
  const { subject, body } = template(q);
  const enc = encodeURIComponent;
  window.open(
    `https://mail.google.com/mail/?view=cm&fs=1&to=${enc(to)}&su=${enc(subject)}&body=${enc(body)}`,
    '_blank',
    'noopener',
  );
}
